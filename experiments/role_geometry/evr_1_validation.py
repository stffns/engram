"""EVR_1 validation on disjoint data -- merken issue #38b.

Pre-registered follow-up to #38. The discovery experiment found that
the eigenvalue spectrum of the residual covariance carries a signal in
the predicted direction when read via EVR_1 (top eigenvalue ratio),
but EVR_1 was named a "consistency check, not independent evidence"
of PR by #38's spec. This script validates EVR_1-as-gate on data
*disjoint* from the discovery set.

Pre-registration (see notes/2026-04-28-residual-geometry-38b-followup-issue.md):

- Primary gate set: knowledge_update_hard.json + two cross-domain
  synthetic scenarios generated by
  experiments/role_geometry/scenarios_disjoint/gen.py from
  vocab_products + vocab_noise_tech and vocab_medical +
  vocab_noise_clinical. Discovery scenarios (knowledge_update_50topics,
  knowledge_update_20topics, knowledge_update.json) are HARD EXCLUDED.

- Two N-modes reported separately: N=4 fixed (forced cluster size)
  and N variable (4-6). Decision rule applies to each independently.

- Three baselines, EVR_1 must beat all three by delta-AUC >= 0.10:
  (1) cluster size N alone -- only meaningful in N-variable mode;
      degenerate at N=4-fixed.
  (2) MaxNormRatio = max(||residual_i||) / mean(||residual_i||).
      O(N) outlier detector; if it matches EVR_1 the spectrum
      interpretation collapses to "one event is far from the rest."
  (3) Mean intra-cluster cosine similarity (carry-over from #38).

- Gate (per N-mode):
  - lower CI > 0.80 AND beats all baselines by 0.10 -> STRONG
  - lower CI 0.65-0.80 AND beats all baselines -> PARTIAL
  - else -> NO_GO

- Cross-embedder: --embed-model flag overrides the vstash default for
  a robustness check on whether the signal is BGE-specific.

Outputs per scenario x N-mode x seed:
  metrics_by_cluster.csv, auc_summary.json
Aggregated summary with joint disposition: aggregate_summary.json.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import logging
import time
from dataclasses import asdict
from pathlib import Path
from typing import Iterable

import numpy as np

from experiments.role_geometry.directional_residual_geometry import (
    Cluster,
    Event,
    bootstrap_auc,
    build_synthetic_clusters,
    cluster_metrics,
    embed_all,
    load_scenario,
    resolve_embedder,
)

logger = logging.getLogger("evr_1_validation")

# Hard-excluded discovery scenarios -- spec line "Discovery scenarios
# MUST NOT appear in the gate computation."
DISCOVERY_SCENARIOS = frozenset(
    {
        "knowledge_update.json",
        "knowledge_update_20topics.json",
        "knowledge_update_50topics.json",
    }
)

# Gate set per #38b spec.
GATE_SCENARIOS = (
    Path("experiments/loop_quality/scenarios/knowledge_update_hard.json"),
    Path("experiments/role_geometry/scenarios_disjoint/generated/products.json"),
    Path("experiments/role_geometry/scenarios_disjoint/generated/medical.json"),
)

K_MIN_FIXED = 4
K_MAX_FIXED = 4
K_MIN_VARIABLE = 4
K_MAX_VARIABLE = 6
N_MIN_CLUSTER = 4


def compute_max_norm_ratio(vectors: np.ndarray, indices: list[int]) -> float:
    """O(N) outlier metric: max(||residual||) / mean(||residual||).

    Captures "is there an outlier event in this cluster" without an
    SVD. Pre-registered as Baseline 2 for #38b: if MaxNormRatio AUC
    matches EVR_1 AUC within 0.05, the eigenvalue interpretation
    collapses to outlier detection.
    """
    sub = vectors[indices]
    centroid = sub.mean(axis=0)
    residuals = sub - centroid
    norms = np.linalg.norm(residuals, axis=1)
    mean_n = norms.mean()
    if mean_n <= 0.0:
        return 1.0
    return float(norms.max() / mean_n)


def compute_extended_metrics(
    vectors: np.ndarray, indices: list[int]
) -> dict[str, float]:
    base = cluster_metrics(vectors, indices)
    base["max_norm_ratio"] = compute_max_norm_ratio(vectors, indices)
    return base


def assert_disjoint(scenario_path: Path) -> None:
    """Hard-stop if the caller passes a discovery scenario."""
    if scenario_path.name in DISCOVERY_SCENARIOS:
        raise RuntimeError(
            f"#38b refuses to run on discovery scenario {scenario_path.name!r}. "
            f"Use the gate set (knowledge_update_hard or scenarios_disjoint/*) instead."
        )


def run_one_mode(
    *,
    events: list[Event],
    vectors: np.ndarray,
    rng: np.random.Generator,
    k_target: int,
    k_min: int,
    k_max: int,
    bootstrap_resamples: int,
    seed: int,
) -> dict:
    """Run one (scenario, N-mode, seed) cell.

    Returns dict with cluster metrics, AUCs, and per-baseline delta-AUC.
    """
    cluster_rng, boot_rng = rng.spawn(2)
    clusters = build_synthetic_clusters(
        events,
        rng=cluster_rng,
        k_target=k_target,
        seed=seed,
        k_min=k_min,
        k_max=k_max,
    )

    excluded = 0
    kept: list[Cluster] = []
    metrics: list[dict[str, float]] = []
    for cl in clusters:
        if len(cl.indices) < N_MIN_CLUSTER:
            excluded += 1
            continue
        kept.append(cl)
        metrics.append(compute_extended_metrics(vectors, cl.indices))

    if not kept:
        return {
            "n_clusters": 0,
            "n_excluded": excluded,
            "aucs": {},
            "delta_aucs": {},
            "decision": "INSUFFICIENT_DATA",
            "n_pos": 0,
            "n_neg": 0,
            "clusters": [],
            "metrics": [],
        }

    is_clean = np.array([1 if c.is_clean else 0 for c in kept])
    is_contam = 1 - is_clean

    metric_arrays = {
        "evr_1": np.array([m["evr_1"] for m in metrics]),
        "pr": np.array([m["pr"] for m in metrics]),
        "ang_disp": np.array([m["ang_disp"] for m in metrics]),
        "norm_var": np.array([m["norm_var"] for m in metrics]),
        "max_norm_ratio": np.array([m["max_norm_ratio"] for m in metrics]),
        "n_alone": np.array([float(m["n"]) for m in metrics]),
        "baseline_neg_cos": -np.array([m["baseline_cos_mean"] for m in metrics]),
    }

    aucs: dict[str, dict[str, float]] = {}
    for name, scores in metric_arrays.items():
        # Skip n_alone bootstrap when N is constant (degenerate).
        if name == "n_alone" and float(np.std(scores)) == 0.0:
            aucs[name] = {
                "roc_auc_mean": float("nan"),
                "roc_auc_lo": float("nan"),
                "roc_auc_hi": float("nan"),
                "pr_auc_mean": float("nan"),
                "pr_auc_lo": float("nan"),
                "pr_auc_hi": float("nan"),
                "n_pos": float(is_contam.sum()),
                "n_neg": float(is_clean.sum()),
                "note": "degenerate (N constant in this mode)",
            }
            continue
        aucs[name] = bootstrap_auc(
            scores=scores,
            labels=is_contam,
            n_resamples=bootstrap_resamples,
            rng=boot_rng,
        )

    primary = aucs["evr_1"]
    delta_aucs: dict[str, float] = {}
    for baseline_name in ("max_norm_ratio", "n_alone", "baseline_neg_cos"):
        b = aucs[baseline_name]
        if np.isnan(b["roc_auc_mean"]):
            delta_aucs[baseline_name] = float("nan")
        else:
            delta_aucs[baseline_name] = (
                primary["roc_auc_mean"] - b["roc_auc_mean"]
            )

    # Gate decision per #38b spec.
    lower_ci = primary["roc_auc_lo"]
    finite_baselines = [d for d in delta_aucs.values() if not np.isnan(d)]
    beats_all = bool(finite_baselines) and all(d >= 0.10 for d in finite_baselines)
    ties_any = bool(finite_baselines) and any(abs(d) < 0.05 for d in finite_baselines)

    if np.isnan(lower_ci):
        decision = "INSUFFICIENT_DATA"
    elif lower_ci > 0.80 and beats_all:
        decision = "STRONG"
    elif lower_ci >= 0.65 and beats_all:
        decision = "PARTIAL"
    elif ties_any:
        decision = "NO_GO_TIES_BASELINE"
    else:
        decision = "NO_GO"

    return {
        "n_clusters": len(kept),
        "n_excluded": excluded,
        "n_pos": int(is_contam.sum()),
        "n_neg": int(is_clean.sum()),
        "aucs": aucs,
        "delta_aucs": delta_aucs,
        "decision": decision,
        "clusters": [asdict(c) for c in kept],
        "metrics": metrics,
    }


def joint_disposition(decision_fixed: str, decision_variable: str) -> str:
    """Joint gate per #38b table."""
    if decision_fixed == "STRONG" and decision_variable == "STRONG":
        return "GO"
    if decision_fixed == "STRONG" and decision_variable != "STRONG":
        return "GO_RESTRICTIVE"
    if decision_variable == "STRONG" and decision_fixed != "STRONG":
        return "INVESTIGATE_FIXED_UNDERPOWERED"
    if decision_fixed == "PARTIAL" or decision_variable == "PARTIAL":
        return "PARTIAL"
    if decision_fixed.startswith("NO_GO") and decision_variable.startswith("NO_GO"):
        return "NO_GO"
    return "MIXED"


def write_metrics_csv(
    out: Path,
    cells: list[tuple[str, int, str, dict]],
    events_per_scenario: dict[str, list[Event]],
) -> None:
    """One row per cluster across (scenario, seed, n_mode) cells."""
    cols = [
        "scenario",
        "seed",
        "n_mode",
        "cluster_id",
        "cluster_class",
        "is_clean",
        "n",
        "evr_1",
        "pr",
        "ang_disp",
        "norm_var",
        "max_norm_ratio",
        "baseline_cos_mean",
    ]
    with out.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        for scenario_name, seed, n_mode, result in cells:
            for cl, m in zip(result["clusters"], result["metrics"]):
                w.writerow(
                    {
                        "scenario": scenario_name,
                        "seed": seed,
                        "n_mode": n_mode,
                        "cluster_id": cl["cluster_id"],
                        "cluster_class": cl["cluster_class"],
                        "is_clean": int(cl["is_clean"]),
                        "n": int(m["n"]),
                        "evr_1": f"{m['evr_1']:.6f}",
                        "pr": f"{m['pr']:.6f}",
                        "ang_disp": f"{m['ang_disp']:.6f}",
                        "norm_var": f"{m['norm_var']:.6f}",
                        "max_norm_ratio": f"{m['max_norm_ratio']:.6f}",
                        "baseline_cos_mean": f"{m['baseline_cos_mean']:.6f}",
                    }
                )


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="output directory; default experiments/role_geometry/runs/38b_<ts>",
    )
    p.add_argument(
        "--seeds",
        type=int,
        nargs="+",
        default=[42, 43, 44],
        help="seeds (default 42 43 44)",
    )
    p.add_argument(
        "--k-target",
        type=int,
        default=20,
        help="target clusters per class per seed (default 20)",
    )
    p.add_argument(
        "--bootstrap-resamples",
        type=int,
        default=1000,
        help="bootstrap resamples for AUC CIs (default 1000)",
    )
    p.add_argument(
        "--scenarios",
        type=Path,
        nargs="*",
        default=None,
        help=(
            "override default gate scenarios; pre-committed default is "
            "knowledge_update_hard + generated/products.json + generated/medical.json. "
            "Discovery scenarios are hard-excluded regardless of this flag."
        ),
    )
    p.add_argument(
        "--embed-model",
        type=str,
        default=None,
        help=(
            "override vstash default embedding model; for cross-embedder check. "
            "Default is None which calls resolve_embedder() (BGE-small typically)."
        ),
    )
    p.add_argument(
        "--log-level",
        default="INFO",
        choices=("DEBUG", "INFO", "WARNING", "ERROR"),
    )
    return p.parse_args(list(argv) if argv is not None else None)


def main(argv: Iterable[str] | None = None) -> int:
    args = parse_args(argv)
    logging.basicConfig(
        level=getattr(logging, args.log_level),
        format="%(asctime)s %(name)s %(levelname)s %(message)s",
    )

    if args.output_dir is None:
        ts = time.strftime("%Y%m%d_%H%M%S")
        args.output_dir = Path("experiments/role_geometry/runs") / f"38b_{ts}"
    args.output_dir.mkdir(parents=True, exist_ok=True)

    scenarios = list(args.scenarios) if args.scenarios else list(GATE_SCENARIOS)
    for s in scenarios:
        assert_disjoint(s)

    model_name = args.embed_model or resolve_embedder()
    logger.info("embedding model: %s", model_name)

    import vstash

    aggregate: dict = {
        "embedding_model": model_name,
        "embedding_model_overridden": args.embed_model is not None,
        "vstash_version": getattr(vstash, "__version__", "unknown"),
        "numpy_version": np.__version__,
        "k_target": args.k_target,
        "bootstrap_resamples": args.bootstrap_resamples,
        "seeds": args.seeds,
        "scenarios": [str(s) for s in scenarios],
        "per_scenario": {},
    }

    cells_for_csv: list[tuple[str, int, str, dict]] = []
    events_per_scenario: dict[str, list[Event]] = {}

    for scenario_path in scenarios:
        scenario_name = scenario_path.name
        logger.info("=== %s ===", scenario_name)
        events = load_scenario(scenario_path)
        events_per_scenario[scenario_name] = events
        vectors = embed_all([e.text for e in events], model_name=model_name)

        per_seed_per_mode: dict[str, dict] = {}
        for seed in args.seeds:
            seed_results: dict = {}
            for n_mode, k_min, k_max in (
                ("n_fixed_4", K_MIN_FIXED, K_MAX_FIXED),
                ("n_variable_4_6", K_MIN_VARIABLE, K_MAX_VARIABLE),
            ):
                root_rng = np.random.default_rng(seed)
                # Per-mode child rng so adding a mode does not shift seeds.
                stage_rng = root_rng.spawn(2)[0 if n_mode == "n_fixed_4" else 1]
                logger.info(
                    "  scenario=%s seed=%d n_mode=%s",
                    scenario_name,
                    seed,
                    n_mode,
                )
                result = run_one_mode(
                    events=events,
                    vectors=vectors,
                    rng=stage_rng,
                    k_target=args.k_target,
                    k_min=k_min,
                    k_max=k_max,
                    bootstrap_resamples=args.bootstrap_resamples,
                    seed=seed,
                )
                seed_results[n_mode] = result
                cells_for_csv.append((scenario_name, seed, n_mode, result))
                logger.info(
                    "    n_clusters=%d evr_1 AUC=%.3f [%.3f, %.3f] "
                    "delta_max_norm=%.3f delta_n=%.3f delta_cos=%.3f -> %s",
                    result["n_clusters"],
                    result["aucs"]["evr_1"]["roc_auc_mean"],
                    result["aucs"]["evr_1"]["roc_auc_lo"],
                    result["aucs"]["evr_1"]["roc_auc_hi"],
                    result["delta_aucs"].get("max_norm_ratio", float("nan")),
                    result["delta_aucs"].get("n_alone", float("nan")),
                    result["delta_aucs"].get("baseline_neg_cos", float("nan")),
                    result["decision"],
                )
            per_seed_per_mode[str(seed)] = seed_results

        # 3-seed aggregation: mean of per-seed AUC and decision counts.
        scenario_summary = {
            "sha256": hashlib.sha256(scenario_path.read_bytes()).hexdigest(),
            "n_events": len(events),
            "per_seed_per_mode": per_seed_per_mode,
        }

        for n_mode in ("n_fixed_4", "n_variable_4_6"):
            evr_1_means = []
            evr_1_los = []
            decisions = []
            for seed in args.seeds:
                r = per_seed_per_mode[str(seed)][n_mode]
                evr_1_means.append(r["aucs"]["evr_1"]["roc_auc_mean"])
                evr_1_los.append(r["aucs"]["evr_1"]["roc_auc_lo"])
                decisions.append(r["decision"])
            scenario_summary[f"{n_mode}_evr_1_mean"] = float(np.mean(evr_1_means))
            scenario_summary[f"{n_mode}_evr_1_stdev"] = (
                float(np.std(evr_1_means, ddof=1)) if len(evr_1_means) > 1 else 0.0
            )
            scenario_summary[f"{n_mode}_evr_1_min_lo"] = float(min(evr_1_los))
            scenario_summary[f"{n_mode}_decisions"] = decisions
            scenario_summary[f"{n_mode}_majority_decision"] = max(
                set(decisions), key=decisions.count
            )

        # Joint disposition uses majority decision per mode.
        scenario_summary["joint_disposition"] = joint_disposition(
            scenario_summary["n_fixed_4_majority_decision"],
            scenario_summary["n_variable_4_6_majority_decision"],
        )
        aggregate["per_scenario"][scenario_name] = scenario_summary
        logger.info(
            "  3-seed: n_fixed_4 EVR_1 mean=%.3f decisions=%s | "
            "n_variable_4_6 EVR_1 mean=%.3f decisions=%s | joint=%s",
            scenario_summary["n_fixed_4_evr_1_mean"],
            scenario_summary["n_fixed_4_decisions"],
            scenario_summary["n_variable_4_6_evr_1_mean"],
            scenario_summary["n_variable_4_6_decisions"],
            scenario_summary["joint_disposition"],
        )

    # Write artifacts.
    write_metrics_csv(
        args.output_dir / "metrics_by_cluster.csv",
        cells_for_csv,
        events_per_scenario,
    )

    # Drop the heavy clusters/metrics arrays from JSON for readability.
    json_aggregate = json.loads(json.dumps(aggregate, default=str))
    for scenario_name, summary in json_aggregate["per_scenario"].items():
        for seed in summary["per_seed_per_mode"]:
            for n_mode in summary["per_seed_per_mode"][seed]:
                cell = summary["per_seed_per_mode"][seed][n_mode]
                cell.pop("clusters", None)
                cell.pop("metrics", None)

    def _scrub(obj: object) -> object:
        if isinstance(obj, dict):
            return {k: _scrub(v) for k, v in obj.items()}
        if isinstance(obj, list):
            return [_scrub(x) for x in obj]
        if isinstance(obj, float) and not np.isfinite(obj):
            return None
        return obj

    (args.output_dir / "aggregate_summary.json").write_text(
        json.dumps(_scrub(json_aggregate), indent=2, allow_nan=False)
    )

    print("\n=== #38b verdict ===")
    print(f"output dir     : {args.output_dir}")
    print(f"embedding model: {model_name}")
    print(f"seeds          : {args.seeds}")
    for scenario_name, summary in aggregate["per_scenario"].items():
        print(f"\n  {scenario_name}")
        print(
            f"    n_fixed_4    : EVR_1 mean={summary['n_fixed_4_evr_1_mean']:.3f} "
            f"min_lo={summary['n_fixed_4_evr_1_min_lo']:.3f} "
            f"-> {summary['n_fixed_4_majority_decision']}"
        )
        print(
            f"    n_variable46 : EVR_1 mean={summary['n_variable_4_6_evr_1_mean']:.3f} "
            f"min_lo={summary['n_variable_4_6_evr_1_min_lo']:.3f} "
            f"-> {summary['n_variable_4_6_majority_decision']}"
        )
        print(f"    joint        : {summary['joint_disposition']}")
    print("====================\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
