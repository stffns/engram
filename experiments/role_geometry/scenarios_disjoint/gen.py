"""Deterministic scenario generator for #38b disjoint validation.

Reads a topic vocabulary (list of {topic, v1, v2, v3}) and a noise
vocabulary (list of templates), shuffles them with a seeded RNG, and
emits a scenario JSON in the same shape as
`experiments/loop_quality/scenarios/knowledge_update_*.json`.

Why scripted (auditable) generation: the topic and noise vocabularies
are committed to git so they can be inspected and reviewed. The
generator itself is short and adds no content -- it only assembles
events, samples noise, and writes the JSON. This protects against the
cherry-picking risk of hand-crafting a scenario that I subconsciously
shape to produce the EVR_1 signal we are validating.

Usage::

    python -m experiments.role_geometry.scenarios_disjoint.gen \\
        --topics-vocab vocab_products.json \\
        --noise-vocab vocab_noise_tech.json \\
        --noise-count 600 \\
        --seed 42 \\
        --out generated/products.json
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path


def generate(
    topic_vocab_path: Path,
    noise_vocab_path: Path,
    out_path: Path,
    *,
    noise_count: int,
    seed: int,
    name: str,
) -> dict:
    topic_vocab = json.loads(topic_vocab_path.read_text())
    noise_vocab = json.loads(noise_vocab_path.read_text())

    topics = topic_vocab["topics"]
    noise_templates: list[str] = noise_vocab["templates"]
    if not topics or not noise_templates:
        raise ValueError("vocab files must be non-empty")

    rng = random.Random(seed)

    events: list[dict] = []
    # Decision events: shuffle topic order, emit v1/v2/v3 in the order
    # they appear in the vocab (the *role* is the version, not the
    # narrative order; downstream role derivation reads the suffix).
    shuffled_topics = list(topics)
    rng.shuffle(shuffled_topics)
    for t in shuffled_topics:
        events.append({"id": f"{t['topic']}_v1", "text": t["v1"], "topic": t["topic"]})
        events.append({"id": f"{t['topic']}_v2", "text": t["v2"], "topic": t["topic"]})
        events.append({"id": f"{t['topic']}_v3", "text": t["v3"], "topic": t["topic"]})

    # Noise events: sample with replacement from templates so the count
    # can exceed template-vocab size; deterministic order via rng.
    for i in range(noise_count):
        text = rng.choice(noise_templates)
        events.append(
            {
                "id": f"noise_{i:04d}",
                "text": text,
                "topic": "noise",
            }
        )

    rng.shuffle(events)  # interleave decisions and noise

    scenario = {
        "name": name,
        "description": (
            f"Generated by experiments/role_geometry/scenarios_disjoint/gen.py "
            f"from {topic_vocab_path.name} + {noise_vocab_path.name} "
            f"with seed={seed}. {len(topics)} decision topics, "
            f"{noise_count} noise events. Topic vocab domain="
            f"{topic_vocab.get('domain', '?')}, noise vocab domain="
            f"{noise_vocab.get('domain', '?')}."
        ),
        "events": events,
        "queries": [],  # no queries needed for residual-geometry test
        "_provenance": {
            "topic_vocab_file": str(topic_vocab_path),
            "noise_vocab_file": str(noise_vocab_path),
            "seed": seed,
            "n_decision_topics": len(topics),
            "n_decision_events": len(topics) * 3,
            "n_noise_events": noise_count,
        },
    }

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(scenario, indent=2) + "\n")
    return scenario


def main() -> int:
    here = Path(__file__).parent
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument(
        "--topics-vocab",
        type=Path,
        required=True,
        help="topic vocabulary JSON path (relative to scenarios_disjoint/ or absolute)",
    )
    p.add_argument(
        "--noise-vocab",
        type=Path,
        required=True,
        help="noise vocabulary JSON path (relative to scenarios_disjoint/ or absolute)",
    )
    p.add_argument("--out", type=Path, required=True, help="output scenario JSON path")
    p.add_argument("--noise-count", type=int, default=600)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--name", type=str, required=True)
    args = p.parse_args()

    def resolve(path: Path) -> Path:
        return path if path.is_absolute() else (here / path).resolve()

    out = resolve(args.out)
    s = generate(
        topic_vocab_path=resolve(args.topics_vocab),
        noise_vocab_path=resolve(args.noise_vocab),
        out_path=out,
        noise_count=args.noise_count,
        seed=args.seed,
        name=args.name,
    )
    print(
        f"wrote {out} -- {len(s['events'])} events "
        f"({s['_provenance']['n_decision_events']} decisions + "
        f"{s['_provenance']['n_noise_events']} noise)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
